<?php

declare(strict_types=1);

namespace BCC\Trust\Onchain\Tests\Unit;

use BCC\Core\Crypto\Bech32;
use BCC\Trust\Onchain\Fetchers\CosmosFetcher;
use BCC\Trust\Tests\Support\LegacyBech32;
use PHPUnit\Framework\Attributes\DataProvider;
use PHPUnit\Framework\TestCase;

/**
 * bcc-trust's lenient Bech32 decoder is replaced by bcc-core's strict one.
 * The bar: NO ADDRESS THE OLD DECODER ACCEPTED STARTS FAILING, unless this
 * file shows why it is not a valid address.
 *
 * Measured against a frozen copy of the old class (tests/Support/LegacyBech32.php):
 *
 *  1. every public address in the fixture (validator operator addresses on
 *     seven chains, CosmWasm contract addresses) decodes to the same HRP and
 *     bytes under both, in both cases, and re-encodes to itself;
 *  2. seeded generated byte strings, under every HRP shape the code meets,
 *     encode identically and decode identically up to the strict length cap;
 *  3. exactly four input classes change answer, each a non-canonical or
 *     impossible string, named and proven invalid below (D1 to D4);
 *  4. nothing the old decoder refused is now accepted;
 *  5. no production code reaches the old class;
 *  6. a caller with no test of its own (CosmosFetcher::valoperToAccountAddress,
 *     the self-delegation lookup) answers as before for every public valoper;
 *  7. the one place the change is visible to a member: a wallet linked in a
 *     second spelling (D3/D4) of the operator's account no longer matches
 *     the validator it names, while the canonical spelling still does;
 *  8. the same at the other two strict call sites: a collection identifier
 *     and a memo-claim valoper in a second spelling are refused.
 */
final class Bech32StrictDecoderDifferentialTest extends TestCase
{
    private const CHARSET = 'qpzry9x8gf2tvdw0s3jn54khce6mua7l';

    /** CosmosFetcher's class constants use the WordPress time constants. */
    public static function setUpBeforeClass(): void
    {
        foreach (['MINUTE_IN_SECONDS' => 60, 'HOUR_IN_SECONDS' => 3600, 'DAY_IN_SECONDS' => 86400] as $name => $value) {
            if (!\defined($name)) {
                \define($name, $value);
            }
        }
    }

    protected function setUp(): void
    {
        parent::setUp();
        require_once dirname(__DIR__) . '/Support/LegacyBech32.php';
    }

    /** @return array<string, list<string>> */
    private static function corpus(): array
    {
        $json = json_decode((string) file_get_contents(dirname(__DIR__) . '/Fixtures/bech32-public-addresses.json'), true);
        self::assertIsArray($json);

        /** @var array<string, list<string>> $addresses */
        $addresses = $json['addresses'];

        return $addresses;
    }

    /** @return iterable<string, array{0: string}> */
    public static function publicAddresses(): iterable
    {
        foreach (self::corpus() as $group => $list) {
            foreach ($list as $i => $address) {
                yield "{$group} #{$i}" => [$address];
            }
        }
    }

    /** A bech32 string with a valid checksum over arbitrary 5-bit values, built with the old helpers. */
    private static function withChecksum(string $hrp, array $values): string
    {
        $polymod = LegacyBech32::polymod(array_merge(LegacyBech32::hrpExpand($hrp), $values, [0, 0, 0, 0, 0, 0])) ^ 1;
        $out     = $hrp . '1';
        foreach ($values as $v) {
            $out .= self::CHARSET[$v];
        }
        for ($i = 0; $i < 6; $i++) {
            $out .= self::CHARSET[($polymod >> (5 * (5 - $i))) & 31];
        }

        return $out;
    }

    // ── 1. The public corpus ────────────────────────────────────────────

    public function testTheCorpusIsTheOneWeThinkItIs(): void
    {
        $count = array_sum(array_map('count', self::corpus()));
        self::assertGreaterThanOrEqual(250, $count, 'anti-vacuity: the fixture holds the public corpus');
    }

    #[DataProvider('publicAddresses')]
    public function testEveryPublicAddressDecodesToTheSameBytes(string $address): void
    {
        foreach ([$address, strtoupper($address)] as $spelling) {
            $legacy = LegacyBech32::decode($spelling);
            self::assertNotNull($legacy, "the old decoder accepted {$spelling}");

            $strict = Bech32::decode($spelling);
            self::assertNotNull($strict, "the strict decoder must accept {$spelling}");
            self::assertSame($legacy['hrp'], $strict['hrp']);
            self::assertSame(LegacyBech32::decodeToBytes($spelling), $strict['bytes']);
        }

        $strict = Bech32::decode($address);
        self::assertNotNull($strict);
        self::assertSame($address, Bech32::encode($strict['hrp'], $strict['bytes']), 'canonical: it re-encodes to itself');
    }

    // ── 2. Generated canonical encodings ────────────────────────────────

    public function testGeneratedEncodingsAgreeAndDecodeAlikeUpToTheCap(): void
    {
        $hrps    = ['a', 'cosmos', 'cosmosvaloper', 'cosmosvalcons', 'cosmosvalconspub', 'osmo', 'osmovaloper', 'juno', 'stars', 'inj', 'injvaloper', 'crocncl', 'thor', 'kujira', 'dungeonvaloper'];
        // 72 and 80 bytes straddle the 128-character cap: under the short
        // HRPs they fit, under the long ones they do not (D1).
        $lengths = [0, 1, 2, 5, 19, 20, 21, 31, 32, 33, 40, 48, 64, 72, 80];

        mt_srand(20261124);
        $decoded = 0;
        $overCap = 0;

        foreach ($hrps as $hrp) {
            foreach ($lengths as $n) {
                for ($round = 0; $round < 4; $round++) {
                    $bytes = '';
                    for ($i = 0; $i < $n; $i++) {
                        $bytes .= chr(mt_rand(0, 255));
                    }

                    $encoded = LegacyBech32::encode($hrp, $bytes);
                    self::assertSame($encoded, Bech32::encode($hrp, $bytes), 'the two encoders are byte-identical');

                    $legacy = LegacyBech32::decodeToBytes($encoded);
                    self::assertSame($bytes, $legacy, 'the old decoder round-trips');

                    if (strlen($encoded) <= 128) {
                        self::assertSame(['hrp' => $hrp, 'bytes' => $bytes], Bech32::decode($encoded), $encoded);
                        $decoded++;
                    } else {
                        // D1, below: only strings no chain issues.
                        self::assertNull(Bech32::decode($encoded));
                        $overCap++;
                    }
                }
            }
        }

        self::assertGreaterThan(600, $decoded, 'anti-vacuity: the generated set is large');
        self::assertGreaterThan(0, $overCap, 'the set reaches past the cap, so D1 is exercised here too');
    }

    // ── 3. The four classes that change answer ──────────────────────────

    /**
     * D1: longer than 128 characters. BIP-173 caps a bech32 string at 90;
     * Cosmos needs more for 32-byte module, ICA and contract addresses, so
     * core caps at 128, which every address a chain issues fits under. A
     * longer string is not an address any chain produces.
     */
    public function testD1AStringOverTheLengthCapIsRefused(): void
    {
        $overlong = LegacyBech32::encode('cosmos', str_repeat("\x42", 100));
        self::assertGreaterThan(128, strlen($overlong));
        self::assertNotNull(LegacyBech32::decode($overlong), 'the old decoder had no cap');
        self::assertNull(Bech32::decode($overlong));

        // The cap's headroom: the longest real shapes still decode.
        foreach (['cosmosvaloper' => 32, 'cosmosvalconspub' => 37, 'dungeonvaloper' => 32] as $hrp => $n) {
            $real = Bech32::encode($hrp, str_repeat("\x07", $n));
            self::assertLessThanOrEqual(128, strlen($real));
            self::assertSame(str_repeat("\x07", $n), Bech32::decode($real)['bytes'] ?? null, $hrp);
        }
    }

    /** @return iterable<string, array{0: string}> */
    public static function nonPrintableHrps(): iterable
    {
        yield 'a space'  => ["cos mos"];
        yield 'DEL'      => ["cos\x7fmos"];
        yield 'a high byte' => ["cos\xc3\xa9mos"];
        yield 'a control byte' => ["cos\x01mos"];
    }

    /**
     * D2: an HRP byte outside printable ASCII. BIP-173 allows HRP characters
     * 33 to 126 only, and every chain's prefix is lowercase letters. The old
     * decoder never looked at the HRP's bytes.
     */
    #[DataProvider('nonPrintableHrps')]
    public function testD2AnHrpByteOutsidePrintableAsciiIsRefused(string $hrp): void
    {
        $encoded = LegacyBech32::encode($hrp, str_repeat("\x11", 20));

        self::assertNotNull(LegacyBech32::decode($encoded), 'the old decoder accepted it');
        self::assertNull(Bech32::decode($encoded));
    }

    /**
     * D3: non-zero padding bits. 19 bytes are 152 bits, carried in 31 groups
     * of 5 (155 bits), so 3 bits are padding and BIP-173 requires them to be
     * zero. Otherwise several different strings name the same bytes, and a
     * comparison of spellings stops meaning a comparison of addresses.
     */
    public function testD3NonZeroPaddingIsRefused(): void
    {
        $bytes  = str_repeat("\x5a", 19);
        $values = LegacyBech32::convertBits(array_values((array) unpack('C*', $bytes)), 8, 5, true);
        self::assertCount(31, $values);

        $canonical = self::withChecksum('cosmos', $values);
        $values[30] |= 0b001;
        $padded    = self::withChecksum('cosmos', $values);
        self::assertNotSame($canonical, $padded);

        self::assertSame($bytes, LegacyBech32::decodeToBytes($padded), 'the old decoder read the same bytes from a second spelling');
        self::assertNull(Bech32::decode($padded));
        self::assertSame($bytes, Bech32::decode($canonical)['bytes'] ?? null, 'the one canonical spelling still decodes');
    }

    /**
     * D4: an excess padding group. 20 bytes fill exactly 32 groups; a 33rd
     * group carries 5 bits that belong to no byte. The old decoder dropped
     * them, so this too was a second spelling of the same 20 bytes.
     */
    public function testD4AnExcessPaddingGroupIsRefused(): void
    {
        $bytes  = str_repeat("\x33", 20);
        $values = LegacyBech32::convertBits(array_values((array) unpack('C*', $bytes)), 8, 5, true);
        self::assertCount(32, $values);

        $canonical = self::withChecksum('cosmosvaloper', $values);
        $values[]  = 0;
        $excess    = self::withChecksum('cosmosvaloper', $values);

        self::assertSame($bytes, LegacyBech32::decodeToBytes($excess), 'the old decoder read the same bytes from a second spelling');
        self::assertNull(Bech32::decode($excess));
        self::assertSame($bytes, Bech32::decode($canonical)['bytes'] ?? null);
    }

    // ── 4. Nothing the old decoder refused is now accepted ──────────────

    /** @return iterable<string, array{0: string}> */
    public static function refusedByBoth(): iterable
    {
        $good = 'cosmosvaloper1qe2s0gguw2khnpfteqy8mhsh5qtmmujfa6fas9';
        yield 'a bad checksum'          => [substr($good, 0, -1) . ($good[-1] === 'q' ? 'p' : 'q')];
        yield 'mixed case'              => ['Cosmosvaloper1qe2s0gguw2khnpfteqy8mhsh5qtmmujfa6fas9'];
        yield 'no separator'            => ['cosmosvaloperqe2s0gguw2khnpfteqy8mhsh5qtmmujfa6fas9'];
        yield 'an empty HRP'            => ['1qe2s0gguw2khnpfteqy8mhsh5qtmmujfa6fas9'];
        yield 'a short checksum'        => ['cosmos1qqqqq'];
        yield 'a character off the set' => ['cosmosvaloper1be2s0gguw2khnpfteqy8mhsh5qtmmujfa6fas9'];
        yield 'empty'                   => [''];
    }

    #[DataProvider('refusedByBoth')]
    public function testWhatTheOldDecoderRefusedStaysRefused(string $input): void
    {
        self::assertNull(LegacyBech32::decode($input));
        self::assertNull(Bech32::decode($input));
    }

    /** Every single-character change to every public address: the strict decoder never accepts what the old one refused. */
    public function testNoSingleCharacterMutantIsNewlyAccepted(): void
    {
        $checked = 0;
        foreach (self::corpus() as $list) {
            foreach ($list as $address) {
                $sep = strrpos($address, '1');
                for ($i = (int) $sep + 1; $i < strlen($address); $i++) {
                    foreach (['q', 'p', 'z', 'l'] as $c) {
                        if ($address[$i] === $c) {
                            continue;
                        }
                        $mutant = substr_replace($address, $c, $i, 1);
                        if (LegacyBech32::decode($mutant) === null) {
                            self::assertNull(Bech32::decode($mutant), $mutant);
                            $checked++;
                        }
                    }
                }
            }
        }

        self::assertGreaterThan(10000, $checked, 'anti-vacuity');
    }

    // ── 5. The old class is gone from production ────────────────────────

    public function testNoProductionCodeReachesTheOldDecoder(): void
    {
        self::assertFileDoesNotExist(dirname(__DIR__, 2) . '/app/Domain/Onchain/Support/Bech32.php');

        $hits = [];
        $it   = new \RecursiveIteratorIterator(new \RecursiveDirectoryIterator(dirname(__DIR__, 2) . '/app', \FilesystemIterator::SKIP_DOTS));
        foreach ($it as $file) {
            if (!$file->isFile() || $file->getExtension() !== 'php') {
                continue;
            }
            $code = '';
            foreach (token_get_all((string) file_get_contents($file->getPathname())) as $t) {
                $code .= is_array($t) ? (in_array($t[0], [T_COMMENT, T_DOC_COMMENT], true) ? '' : $t[1]) : $t;
            }
            if (str_contains($code, 'Onchain\\Support\\Bech32') || preg_match('/\buse\s+BCC\\\\Core\\\\Crypto\\\\Bech32\s*;/', $code) === 1) {
                $hits[basename($file->getPathname())] = str_contains($code, 'Onchain\\Support\\Bech32') ? 'OLD' : 'core';
            }
        }

        self::assertNotContains('OLD', $hits, 'nothing references the deleted class');
        ksort($hits);
        self::assertSame(
            ['ClaimService.php' => 'core', 'CosmosFetcher.php' => 'core', 'CosmosTxInclusionFetcher.php' => 'core', 'NftCollectionIdentifier.php' => 'core'],
            $hits,
            'the four callers decode through bcc-core'
        );
    }

    // ── 6. A caller with no test of its own ─────────────────────────────

    /** The real CosmosFetcher, constructor bypassed: the method reads no property. */
    private static function fetcher(): CosmosFetcher
    {
        /** @var CosmosFetcher $f */
        $f = (new \ReflectionClass(CosmosFetcher::class))->newInstanceWithoutConstructor();

        return $f;
    }

    /** @return iterable<string, array{0: string}> */
    public static function publicValopers(): iterable
    {
        foreach (self::corpus() as $group => $list) {
            if (!str_starts_with($group, 'valoper:')) {
                continue;
            }
            foreach ($list as $i => $address) {
                yield "{$group} #{$i}" => [$address];
            }
        }
    }

    #[DataProvider('publicValopers')]
    public function testValoperToAccountAddressAnswersAsBefore(string $valoper): void
    {
        $pos = strpos($valoper, 'valoper1');
        if ($pos === false) {
            // Crypto.org's `crocncl`: no `valoper` HRP, refused before any decode, as before.
            self::assertNull(self::fetcher()->valoperToAccountAddress($valoper));
            return;
        }

        $expected = LegacyBech32::encode(substr($valoper, 0, $pos), (string) LegacyBech32::decodeToBytes($valoper));
        self::assertSame($expected, self::fetcher()->valoperToAccountAddress($valoper));
    }

    public function testValoperToAccountAddressRefusesWhatTheStrictDecoderRefuses(): void
    {
        $good = 'cosmosvaloper1qe2s0gguw2khnpfteqy8mhsh5qtmmujfa6fas9';
        self::assertNotNull(self::fetcher()->valoperToAccountAddress($good));
        self::assertNull(self::fetcher()->valoperToAccountAddress(substr($good, 0, -1) . 'q'), 'a bad checksum');

        // A second spelling of 19 bytes (D3): the old decoder derived an account from it.
        $values      = LegacyBech32::convertBits(array_values((array) unpack('C*', str_repeat("Z", 19))), 8, 5, true);
        $values[30] |= 0b001;
        $padded      = self::withChecksum('cosmosvaloper', $values);
        self::assertNotNull(LegacyBech32::decodeToBytes($padded));
        self::assertNull(self::fetcher()->valoperToAccountAddress($padded));
    }

    // ── 7. ClaimService: a second spelling no longer matches ────────────

    /** @param list<string> $wallets */
    private static function claimMatch(array $wallets, string $valoper): ?array
    {
        $objs = [];
        foreach ($wallets as $address) {
            $objs[] = (object) ['wallet_address' => $address, 'chain_id' => 8];
        }
        $m = new \ReflectionMethod('BCC\Trust\Onchain\Services\ClaimService', 'matchValidator');
        $m->setAccessible(true);

        /** @var array{wallet_address: string, chain_id: int, role: string}|null $out */
        $out = $m->invoke(null, $objs, (object) ['operator_address' => $valoper, 'chain_type' => 'cosmos']);

        return $out;
    }

    public function testAWalletInASecondSpellingNoLongerMatchesItsValidator(): void
    {
        $bytes   = str_repeat("\x2c", 20);
        $valoper = Bech32::encode('cosmosvaloper', $bytes);
        $values  = LegacyBech32::convertBits(array_values((array) unpack('C*', $bytes)), 8, 5, true);

        $canonical = self::withChecksum('cosmos', $values);
        $excess    = self::withChecksum('cosmos', array_merge($values, [0]));
        self::assertSame($bytes, LegacyBech32::decodeToBytes($excess), 'the old decoder read the operator bytes from it');

        self::assertNotNull(self::claimMatch([$canonical], $valoper), 'the canonical spelling still matches');
        self::assertNull(self::claimMatch([$excess], $valoper), 'a second spelling (D4) no longer does');
    }

    // ── 8. The other strict call sites refuse a second spelling too ─────

    public function testACollectionContractInASecondSpellingIsRefused(): void
    {
        $bytes  = str_repeat("\x61", 32);
        $values = LegacyBech32::convertBits(array_values((array) unpack('C*', $bytes)), 8, 5, true);
        $values[count($values) - 1] |= 0b0001; // 256 bits in 52 groups: 4 padding bits, one set (D3)

        $canonical = Bech32::encode('juno', $bytes);
        $padded    = self::withChecksum('juno', $values);
        self::assertSame($bytes, LegacyBech32::decodeToBytes($padded), 'the old decoder read the contract bytes from it');

        self::assertTrue(\BCC\Trust\Onchain\Support\NftCollectionIdentifier::canonicalize('cosmos', $canonical)->isAccepted());
        self::assertFalse(\BCC\Trust\Onchain\Support\NftCollectionIdentifier::canonicalize('cosmos', $padded)->isAccepted());
    }

    public function testAMemoClaimValoperInASecondSpellingIsRefused(): void
    {
        $bytes   = str_repeat("\x19", 20);
        $values  = LegacyBech32::convertBits(array_values((array) unpack('C*', $bytes)), 8, 5, true);
        $excess  = self::withChecksum('cosmosvaloper', array_merge($values, [0]));
        $fetcher = 'BCC\Trust\Onchain\Services\CosmosTxInclusionFetcher';

        self::assertSame(Bech32::encode('cosmos', $bytes), $fetcher::operatorAccount(Bech32::encode('cosmosvaloper', $bytes), 'cosmos'));
        self::assertSame($bytes, LegacyBech32::decodeToBytes($excess), 'the old decoder read the operator bytes from it');
        self::assertNull($fetcher::operatorAccount($excess, 'cosmos'));
    }
}
